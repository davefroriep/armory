// Bumps the visible revision badge (src/rev.ts) and the Service Worker cache name (public/sw.js).
// Runs automatically as the first step of `npm run build` so every deploy ships a new rev.
import fs from 'node:fs';

const r = JSON.parse(fs.readFileSync('rev.json', 'utf8'));
r.build += 1;
const d = new Date();
const pad = (n) => String(n).padStart(2, '0');
const stamp = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}`;
const rev = `v${r.major}.${r.build}`;

fs.writeFileSync('rev.json', JSON.stringify(r) + '\n');
fs.writeFileSync(
  'src/rev.ts',
  `// generated by scripts/bump-rev.mjs - do not edit\nexport const REV = '${rev}';\nexport const REV_STAMP = '${stamp}';\n`,
);
const sw = fs.readFileSync('public/sw.js', 'utf8').replace(/const CACHE = '.*?';/, `const CACHE = 'armory-fit-v${r.build}';`);
fs.writeFileSync('public/sw.js', sw);
console.log(`Rev ${rev} - ${stamp} (cache armory-fit-v${r.build})`);
