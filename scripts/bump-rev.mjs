// Bumps the visible revision badge (src/rev.ts) and Android APK versionCode / versionName (android/app/build.gradle).
// Runs automatically as the first step of `npm run build` so every APK build tracks a matching version.
import fs from 'node:fs';

const r = JSON.parse(fs.readFileSync('rev.json', 'utf8'));
r.build += 1;
const d = new Date();
const pad = (n) => String(n).padStart(2, '0');
const stamp = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}`;
const rev = `v${r.major}.${r.build}`;
const semver = `${r.major}.${r.build}`;

fs.writeFileSync('rev.json', JSON.stringify(r) + '\n');
fs.writeFileSync(
  'src/rev.ts',
  `// generated by scripts/bump-rev.mjs - do not edit\nexport const REV = '${rev}';\nexport const REV_STAMP = '${stamp}';\n`,
);

const gradlePath = 'android/app/build.gradle';
if (fs.existsSync(gradlePath)) {
  const gradle = fs.readFileSync(gradlePath, 'utf8')
    .replace(/versionCode\s+\d+/, `versionCode ${r.build}`)
    .replace(/versionName\s+"[^"]*"/, `versionName "${semver}"`);
  fs.writeFileSync(gradlePath, gradle);
}

console.log(`Rev ${rev} - ${stamp} (Android versionCode ${r.build})`);
